// Run: node tests/model.test.js   (from the plugin folder)
const fs = require("fs"), path = require("path"), assert = require("assert")
const src = fs.readFileSync(path.join(__dirname, "..", "Model.js"), "utf8").replace(".pragma library", "")
const M = new Function(src + "; return { parse, status, icon, lit, statusKey, hintKey, techLabel, humanBytes, shortModel, canConnect, canDisconnect, signalPercent }")()

const base = { present: "yes", radio: "enabled", sim: "yes", state: "enabled" }
const st = o => M.status(Object.assign({}, base, o))

assert.strictEqual(M.status({ present: "no" }), "absent")
assert.strictEqual(st({ radio: "disabled" }), "off")
assert.strictEqual(st({ state: "disabled" }), "off")
assert.strictEqual(st({ state: "failed", failed_reason: "sim-missing" }), "no-sim")
assert.strictEqual(st({ sim: "no" }), "no-sim")
assert.strictEqual(st({ state: "locked" }), "locked")
// The unactivated-SIM case on this laptop:
assert.strictEqual(st({ registration: "idle", device_state: "connecting (prepare)" }), "no-service")
assert.strictEqual(st({ registration: "denied" }), "denied")
assert.strictEqual(st({ registration: "searching", state: "searching" }), "searching")
assert.strictEqual(st({ state: "registered", registration: "home", device_state: "disconnected" }), "registered")
assert.strictEqual(st({ state: "registered", registration: "home", device_state: "connecting (ip-config)" }), "connecting")
assert.strictEqual(st({ state: "connected", registration: "home", device_state: "connected" }), "connected")
assert.strictEqual(M.statusKey("registered", { registration: "roaming" }), "status.roaming")
assert.strictEqual(M.hintKey("no-service"), "hint.noService")
assert.strictEqual(M.lit("connected"), true)
assert.strictEqual(M.lit("registered"), false)

assert.strictEqual(M.techLabel("lte"), "LTE")
assert.strictEqual(M.techLabel("umts,hsdpa"), "3G+")
assert.strictEqual(M.techLabel("5gnr,lte"), "5G")
assert.strictEqual(M.techLabel(""), "")
assert.strictEqual(M.humanBytes("1536"), "1.5 KB")
assert.strictEqual(M.humanBytes("0"), "0 B")
assert.strictEqual(M.humanBytes("x"), "")
assert.strictEqual(M.shortModel("Sierra Wireless EM7455 Qualcomm® Snapdragon™ X7 LTE-A"), "Sierra Wireless EM7455")
assert.strictEqual(M.signalPercent({ signal: "250" }), 100)
assert.notStrictEqual(M.icon("connected", { signal: "90" }), M.icon("connected", { signal: "10" }))
assert.strictEqual(M.canConnect("registered", { profile: "Mobile Broadband" }), true)
assert.strictEqual(M.canConnect("no-service", { profile: "Mobile Broadband" }), false)
assert.strictEqual(M.canDisconnect("connected", { device: "cdc-wdm0" }), true)

// Parser: tabs split key/value, junk keys dropped, markup kept as plain text, long values capped.
const p = M.parse("radio\tenabled\nBad Key\tx\nnotab\noperator\t<img src=x>\nmodel\t" + "a".repeat(1000))
assert.strictEqual(p.radio, "enabled")
assert.strictEqual(p["Bad Key"], undefined)
assert.strictEqual(p.operator, "<img src=x>")
assert.strictEqual(p.model.length, 256)
console.log("all model tests passed")
